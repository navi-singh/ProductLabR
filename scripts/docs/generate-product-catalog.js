#!/usr/bin/env node
/**
 * Generates docs/PRODUCT-CATALOG.md: every reviewed product grouped by
 * category and a derived subcategory. Posts carry no subcategory field, so it
 * is inferred from capacity (power stations) or the product name.
 *
 * Usage: npm run docs:catalog
 */
const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const ROOT = path.join(__dirname, '..', '..');
const POSTS_DIR = path.join(ROOT, 'posts');
const OUT = path.join(ROOT, 'docs', 'PRODUCT-CATALOG.md');

function categoryNames() {
  const src = fs.readFileSync(path.join(ROOT, 'lib', 'taxonomy.ts'), 'utf8');
  const names = {};
  const re = /contentDir:\s*'([^']+)',\s*name:\s*'([^']+)'/g;
  let m;
  while ((m = re.exec(src))) names[m[1]] = m[2];
  return names;
}

function productName(title) {
  return String(title)
    .split(':')[0]
    .replace(/\s+Review$/i, '')
    .trim();
}

function capacityWh(data) {
  if (Number(data.capacityWh) > 0) return Number(data.capacityWh);
  for (const [key, value] of Object.entries(data.specs || {})) {
    if (!/capacity|battery/i.test(key)) continue;
    const m = String(value).match(/([\d.,]+)\s*(k?Wh)\b/i);
    if (!m) continue;
    const n = Number(m[1].replace(/,/g, ''));
    return /kwh/i.test(m[2]) ? n * 1000 : n;
  }
  return null;
}

const RULES = {
  'portable-power-stations': (name, data) => {
    if (/redemption/i.test(name)) return 'Brand overview';
    if (/AC500/i.test(name)) return 'Home backup (3kWh+)';
    const wh = capacityWh(data);
    if (wh === null) return 'Unclassified';
    if (wh < 200) return 'Power banks & travel chargers (<200Wh)';
    if (wh < 1000) return 'Compact (200–999Wh)';
    if (wh < 2000) return 'Mid-size (1–2kWh)';
    if (wh < 3000) return 'Large (2–3kWh)';
    return 'Home backup (3kWh+)';
  },
  'smart-generators': () => 'Smart generators',
  headphones: (name) =>
    /buds|airpods(?!\s*max)|WF-|elite|nothing ear/i.test(name)
      ? 'Wireless earbuds'
      : 'Over-ear headphones',
  cameras: (name) => {
    if (/GFX|Hasselblad/i.test(name)) return 'Medium format';
    if (/Leica M/i.test(name)) return 'Rangefinder';
    if (/X-H2S/i.test(name)) return 'APS-C mirrorless';
    return 'Full-frame mirrorless';
  },
  gaming: (name) => (/K\d{3}|Apex|G915|keyboard/i.test(name) ? 'Keyboards' : 'Mice'),
  laptops: (name) => {
    if (/MacBook/i.test(name)) return 'MacBooks';
    if (/ROG|Legion|Titan|Razer Blade/i.test(name)) return 'Gaming laptops';
    return 'Everyday & budget laptops';
  },
  monitors: (name) =>
    /AOC|ROG|UltraGear|Odyssey/i.test(name)
      ? 'Gaming monitors'
      : 'Professional & creative monitors',
  'smart-home': (name) =>
    /Echo|HomePod|Nest Audio/i.test(name) ? 'Smart speakers' : 'Robot vacuums',
  thermostats: () => 'Smart thermostats',
  tvs: (name) => {
    if (/Frame/i.test(name)) return 'Lifestyle TVs';
    if (/OLED/i.test(name) && !/QNED/i.test(name)) return 'OLED TVs';
    if (/Mini-LED|QLED|QNED|Quantum|Bravia 9|X90L|QM8|U8K|U7N/i.test(name))
      return 'Mini-LED & QLED TVs';
    return 'Budget LED TVs';
  },
  wearables: (name) => {
    if (/Charge/i.test(name)) return 'Fitness trackers';
    if (/Fenix|Forerunner|Polar|Ultra/i.test(name)) return 'Sports & outdoor watches';
    return 'Smartwatches';
  },
  'knives-tools': () => 'Pocket knives',
};

function main() {
  const names = categoryNames();
  const rows = [];

  for (const dir of fs.readdirSync(POSTS_DIR).sort()) {
    const full = path.join(POSTS_DIR, dir);
    if (!fs.statSync(full).isDirectory()) continue;
    for (const file of fs.readdirSync(full).filter((f) => f.endsWith('.md'))) {
      const { data } = matter(fs.readFileSync(path.join(full, file), 'utf8'));
      const product = productName(data.title || file);
      const rule = RULES[dir];
      rows.push({
        category:
          names[dir] ||
          dir
            .split('-')
            .map((w) => w[0].toUpperCase() + w.slice(1))
            .join(' '),
        subcategory: rule ? rule(product, data) : 'Unclassified',
        product,
        link: `../posts/${dir}/${file}`,
      });
    }
  }

  rows.sort(
    (a, b) =>
      a.category.localeCompare(b.category) ||
      a.subcategory.localeCompare(b.subcategory) ||
      a.product.localeCompare(b.product),
  );

  const counts = {};
  for (const r of rows) counts[r.category] = (counts[r.category] || 0) + 1;

  const esc = (s) => s.replace(/\|/g, '\\|');
  const lines = [
    '# Product Catalog',
    '',
    '<!-- Generated by scripts/docs/generate-product-catalog.js. Do not edit by hand; run `npm run docs:catalog`. -->',
    '',
    `Every product with a published review: **${rows.length}** products across **${Object.keys(counts).length}** categories.`,
    '',
    'Subcategories are derived (posts have no subcategory field): power stations are tiered by battery capacity; other categories are grouped by product type.',
    '',
    '## Summary',
    '',
    '| Category | Products |',
    '| --- | ---: |',
    ...Object.entries(counts).map(([c, n]) => `| ${esc(c)} | ${n} |`),
    '',
    '## All products',
    '',
    '| Category | Subcategory | Product |',
    '| --- | --- | --- |',
    ...rows.map(
      (r) => `| ${esc(r.category)} | ${esc(r.subcategory)} | [${esc(r.product)}](${r.link}) |`,
    ),
    '',
  ];

  fs.writeFileSync(OUT, lines.join('\n'));
  const unclassified = rows.filter((r) => r.subcategory === 'Unclassified');
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${rows.length} products).`);
  if (unclassified.length) {
    console.warn(`Unclassified: ${unclassified.map((r) => r.product).join(', ')}`);
  }
}

main();
